# RESULTS VISUALISATION FOR QTIM COHORT (HEATMAPS)
# ==============================================================================

# 1. LOAD LIBRARIES
import pandas as pd
import numpy as np
import seaborn as sns
import matplotlib.pyplot as plt
import os

# ==============================================================================
# 2. USER CONFIGURATION
# ==============================================================================
input_dir = "./data/output/"
output_dir = "./data/output/figures/"

# Ensure output directory for figures exists
os.makedirs(output_dir, exist_ok=True)

# Input CSV files generated by the 02_QTIM_Linear_Mixed_Models.R script
sbayes_m1_file = f"{input_dir}qtim_results_sbayesrc_model1_rsqmarg.csv"
ct_m1_file     = f"{input_dir}qtim_results_ct_model1_rsqmarg.csv"
sbayes_m2_file = f"{input_dir}qtim_results_sbayesrc_model2_rsqmarg.csv"
ct_m2_file     = f"{input_dir}qtim_results_ct_model2_rsqmarg.csv"

# Define Regions of Interest
RoiCodes = ['Accumbens', 'Amygdala', 'Brainstem', 'Caudate', 'Hippocampus', 
            'Pallidum', 'Putamen', 'Thalamus', 'ventralDC', 'ICV']

# Dictionary to format region names for the final plot
rename_dict = {
    'ventralDC': 'Ventral Diencephalon', 
    'ICV': 'Intracranial Volume', 
    'Accumbens': 'Nucleus accumbens', 
    'Caudate': 'Caudate Nucleus', 
    'Pallidum': 'Globus Pallidus'
}

# ==============================================================================
# 3. HELPER FUNCTIONS
# ==============================================================================

def create_heatmap_data(df_sbayes, df_ct, roi_codes, n_corrections):
    """
    Extracts R2 and P-values from the dataframes, formats them for the heatmap,
    and applies significance annotations (* for p<=0.05, ** for Bonferroni).
    """
    R2_data = pd.DataFrame(columns=roi_codes)
    P_data = pd.DataFrame(columns=roi_codes)

    # FIX: Use .set_index('ROI') instead of .values to force pandas to align the 
    # columns by name. This prevents size mismatches when 'ICV' is dropped.
    R2_data.loc['SbayesRC'] = df_sbayes.set_index('ROI')['Rsq'].astype(float) * 100
    P_data.loc['SbayesRC'] = df_sbayes.set_index('ROI')['P'].astype(float)

    # Extract C+T thresholds data
    for thr in df_ct['Threshold'].unique():
        df_thr = df_ct[df_ct['Threshold'] == thr]
        R2_data.loc[thr] = df_thr.set_index('ROI')['Variance Explained (%)'].astype(float)
        P_data.loc[thr] = df_thr.set_index('ROI')['P-value'].astype(float)

    # Generate significance annotations safely
    annotations = P_data.copy().astype(str)
    annotations[:] = ''
    
    # Apply thresholds for significance
    for col in P_data.columns:
        for idx in P_data.index:
            p_val = P_data.loc[idx, col]
            if pd.notna(p_val): # Added safety check for missing values
                if p_val <= 0.05 / n_corrections:
                    annotations.loc[idx, col] = '**'
                elif p_val <= 0.05:
                    annotations.loc[idx, col] = '*'

    print(f"Applied Bonferroni correction for {n_corrections} tests.")
    return R2_data, annotations

def plot_heatmap(data, annotations, filename_base, vmin=0, vmax=2):
    """
    Generates and saves the heatmap visualisation in SVG, PDF, and PNG formats.
    """
    sns.set_theme(font_scale=1.4, style='whitegrid')
    
    fig, ax = plt.subplots(figsize=(10, 10))
    cmap = sns.cubehelix_palette(as_cmap=True, rot=.2)

    sns.heatmap(
        data, 
        cmap=cmap, 
        ax=ax, 
        vmin=vmin, 
        vmax=vmax,
        annot=annotations, 
        fmt="", 
        cbar_kws={
            'label': 'Variance explained (%)', 
            'orientation': 'horizontal', 
            'location': 'top'
        }
    )

    # Format Y-axis labels with LaTeX styling for p-values
    y_labels = ['SbayesRC'] + [f'$p \\leq {thr}$' for thr in ['5e-08', '1e-05', '0.001', '0.01', '0.05', '0.1', '0.5', '1.0']]
    ax.set_yticklabels(y_labels, rotation=0)
    ax.set_xlabel('')
    ax.set_ylabel('')
    
    plt.tight_layout()
    
    # Save figures
    for ext in ['svg', 'pdf', 'png']:
        filepath = f"{output_dir}{filename_base}.{ext}"
        fig.savefig(filepath, transparent=True, bbox_inches='tight')
        
    print(f"Successfully saved {filename_base} to {output_dir}")
    plt.close()

# ==============================================================================
# 4. DATA PROCESSING AND VISUALISATION
# ==============================================================================

if __name__ == "__main__":
    
    # Load statistical outputs
    df_sbayes1 = pd.read_csv(sbayes_m1_file)
    df_CT1     = pd.read_csv(ct_m1_file)
    df_sbayes2 = pd.read_csv(sbayes_m2_file)
    df_CT2     = pd.read_csv(ct_m2_file)

    # ---------------------------------------------------------
    # MODEL 1: Without ICV as a covariate
    # Corrections: 9 thresholds * 10 ROIs (includes ICV) = 90
    # ---------------------------------------------------------
    print("\n=== GENERATING MODEL 1 HEATMAP ===")
    R2_data1, DFstar1 = create_heatmap_data(df_sbayes1, df_CT1, RoiCodes, n_corrections=90)
    
    plot_heatmap(
        R2_data1.rename(columns=rename_dict), 
        DFstar1.rename(columns=rename_dict), 
        filename_base='Model1_QTIM_PRS_Heatmap', 
        vmin=0, vmax=2
    )

    # ---------------------------------------------------------
    # MODEL 2: With ICV as a covariate
    # Corrections: 9 thresholds * 9 ROIs (excluding ICV) = 81
    # ---------------------------------------------------------
    print("\n=== GENERATING MODEL 2 HEATMAP ===")
    
    # We remove ICV from the RoI list for Model 2 since it was moved to a covariate
    RoiCodes_noICV = [roi for roi in RoiCodes if roi != 'ICV']
    
    R2_data2, DFstar2 = create_heatmap_data(df_sbayes2, df_CT2, RoiCodes_noICV, n_corrections=81)

    plot_heatmap(
        R2_data2.rename(columns=rename_dict), 
        DFstar2.rename(columns=rename_dict), 
        filename_base='Model2_QTIM_PRS_Heatmap_ICV', 
        vmin=0, vmax=2
    )
    
    print("\nAll visualisations completed.")
